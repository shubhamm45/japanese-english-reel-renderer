"""Render one bilingual (English-teaches-Japanese) lesson and publish a manifest.

Lesson JSON schema:
  title, phrase, phrase_romaji, meaning_en, usage_en, example, example_en,
  say_it, get_it, use_it  (English narration scripts, Japanese words embedded),
  narration_audio: {say_it, get_it, use_it} (Qwen TTS voiceover URLs, fail-closed),
  level, category, topic, caption

Cards are bilingual: Japanese phrase big + romaji/English below; the voiceover
narrates in English (Qwen TTS, generated by n8n and passed as URLs).

Fonts: Noto Sans CJK covers Japanese (hiragana, katakana, kanji) but its
glyph shapes are region-specific, so text is drawn in per-script runs:
Japanese runs use the fontconfig-resolved JP face of Noto Sans CJK,
Latin runs use Noto Sans. Requires fonts-noto-cjk - DejaVu cannot render
Japanese.
"""
import argparse
import json
import os
from functools import lru_cache
from pathlib import Path
import re
import subprocess
import tempfile
from datetime import datetime, timezone
from PIL import Image, ImageDraw, ImageFont


def run(args):
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


LIMITS = {
    "title": 100, "phrase": 180, "phrase_romaji": 120,
    "meaning_en": 180, "usage_en": 300,
    "example": 180, "example_en": 180,
    "say_it": 200, "get_it": 120, "use_it": 260,
}


def validate(lesson, request_id):
    if not re.fullmatch(r"[A-Za-z0-9_-]{8,80}", request_id):
        raise ValueError("request_id must be 8-80 letters, digits, underscores or hyphens")
    if not isinstance(lesson, dict):
        raise ValueError("lesson must be a JSON object")
    for key, limit in LIMITS.items():
        value = lesson.get(key)
        if not isinstance(value, str) or not value.strip() or len(value) > limit:
            raise ValueError(f"{key} must be nonempty text, at most {limit} characters")
    if any(ord(c) < 32 and c not in '\n\t' for v in lesson.values() if isinstance(v, str) for c in v):
        raise ValueError("Control characters are not allowed")


_RAQM = getattr(ImageFont.Layout, "RAQM", None)


def _load(path, size, index=0):
    # RAQM improves complex-script shaping where available; fall back to
    # the basic layout engine if libraqm is unavailable.
    kwargs = {"layout_engine": _RAQM} if _RAQM is not None else {}
    try:
        return ImageFont.truetype(path, size, index=index, **kwargs)
    except Exception:
        return ImageFont.truetype(path, size, **kwargs)


def _first_existing(candidates):
    for path in candidates:
        if path and Path(path).exists():
            return path
    return None


def _fc_match_ja(bold):
    """Resolve the Japanese regional face of Noto Sans CJK via fontconfig.
    Returns (path, index) or None. The per-weight NotoSansCJK .ttc files are
    collections; the JP face index is what fontconfig picks for :lang=ja."""
    try:
        out = run(["fc-match", f":lang=ja:weight={'bold' if bold else 'regular'}",
                   "--format=%{file}|%{index}\n"]).strip()
        path, _, idx = out.partition("|")
        if path and Path(path).exists():
            return path, int(idx or 0)
    except Exception:
        pass
    return None


@lru_cache(maxsize=256)
def font_ja(size, bold=False):
    """Japanese-capable font: the JP face of Noto Sans CJK."""
    resolved = _fc_match_ja(bold)
    if resolved:
        path, index = resolved
        return _load(path, size, index=index)
    ttc = ("/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc" if bold
           else "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc")
    path = _first_existing([os.environ.get("REEL_FONT_JA", ""), ttc])
    if not path:
        raise RuntimeError("Install fonts-noto-cjk or set REEL_FONT_JA to a Japanese .ttf/.otf/.ttc font")
    return _load(path, size)


@lru_cache(maxsize=256)
def font_lat(size, bold=False):
    """Latin font for English text."""
    lat = ("/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf" if bold
           else "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf")
    path = _first_existing([lat,
        f"/usr/share/fonts/truetype/dejavu/DejaVuSans{'-Bold' if bold else ''}.ttf",
        f"/System/Library/Fonts/Supplemental/Arial{' Bold' if bold else ''}.ttf"])
    if not path:
        raise RuntimeError("Install fonts-noto-core (or DejaVu)")
    return _load(path, size)


def _is_ja(ch):
    o = ord(ch)
    return (0x3040 <= o <= 0x30FF or   # hiragana + katakana
            0x3400 <= o <= 0x4DBF or   # CJK extension A
            0x4E00 <= o <= 0x9FFF or   # CJK unified ideographs
            0xF900 <= o <= 0xFAFF or   # CJK compatibility ideographs
            0x3000 <= o <= 0x303F or   # CJK symbols and punctuation
            0xFF00 <= o <= 0xFFEF)     # halfwidth/fullwidth forms


def runs(text):
    """Split text into (is_japanese, segment) runs for per-script fonts."""
    out, buf, cur = [], [], None
    for ch in text:
        is_ja = _is_ja(ch)
        if cur is None or is_ja == cur:
            buf.append(ch)
            cur = is_ja
        else:
            out.append((cur, "".join(buf)))
            buf, cur = [ch], is_ja
    if buf:
        out.append((cur, "".join(buf)))
    return out


def measure(draw, text, size, bold=False):
    """Total width of mixed-script text at the given size."""
    total = 0
    for is_ja, seg in runs(text):
        face = font_ja(size, bold) if is_ja else font_lat(size, bold)
        total += draw.textlength(seg, font=face)
    return total


def dtext(d, xy, text, size, bold=False, fill=None):
    """Draw text, switching fonts per script run so mixed Japanese/English
    never renders as tofu boxes."""
    x, y = xy
    for is_ja, seg in runs(text):
        face = font_ja(size, bold) if is_ja else font_lat(size, bold)
        d.text((x, y), seg, font=face, fill=fill)
        x += d.textlength(seg, font=face)


def wrap(draw, text, size, bold, width):
    lines = []
    for paragraph in text.splitlines() or [text]:
        line = ""
        for word in paragraph.split():
            proposed = f"{line} {word}".strip()
            if measure(draw, proposed, size, bold) <= width:
                line = proposed
            else:
                if line:
                    lines.append(line)
                line = ""
                for char in word:
                    if measure(draw, line + char, size, bold) > width:
                        lines.append(line)
                        line = char
                    else:
                        line += char
        if line:
            lines.append(line)
    return lines


def fit_block(draw, text, width, max_height, start_size, min_size, bold=True):
    """Shrink font until the wrapped text fits max_height. Returns (size, lines).
    Also avoids a single-character orphan on the last line when shrinking can
    fix it (common with spaceless Japanese text)."""
    size = start_size
    while True:
        lines = wrap(draw, text, size, bold, width)
        fits = len(lines) * (size + 18) <= max_height
        orphan = len(lines) > 1 and len(lines[-1].strip()) <= 1
        if fits and not orphan:
            return size, lines
        if size <= min_size:
            if fits:
                return size, lines  # fits vertically; accept a short last line
            raise ValueError("Text cannot fit on a card")
        size -= 2


def card(label, primary, secondary, title, index, dest):
    # Keep key content inside the central safe area for Reel controls/captions.
    cream, ink, coral, mint = "#f5f1e8", "#172b29", "#ff704f", "#c9e9d7"
    im = Image.new("RGB", (1080, 1920), cream)
    d = ImageDraw.Draw(im)
    d.ellipse((730, -160, 1240, 350), fill=mint)
    d.ellipse((-180, 1480, 300, 1960), fill="#eadfcf")
    # Small editorial masthead and lesson number.
    d.rounded_rectangle((88, 170, 408, 226), radius=28, fill=ink)
    dtext(d, (111, 182), "DAILY / JAPANESE", 27, True, cream)
    dtext(d, (88, 244), "@japanesewithenglish.learn", 24, True, "#5d706a")
    dtext(d, (815, 180), f"0{index} / 03", 28, True, ink)
    headlines = ["今日のフレーズ", "意味を理解する", "実用的な例文"]
    endings = ["こう言うよ。", "しっかり理解しよう。", "練習してみよう。"]
    dtext(d, (88, 290), headlines[index-1], 92, True, ink)
    dtext(d, (88, 395), endings[index-1], 92, True, coral)
    panel = (88, 570, 944, 1180)
    fill = [ink, mint, coral][index-1]
    fg = cream if index == 1 else ink
    # Offset shadow adds depth without a large empty enclosing card.
    d.rounded_rectangle((100, 584, 956, 1194), radius=38, fill="#ddd4c5")
    d.rounded_rectangle(panel, radius=38, fill=fill)
    small_label = ["日本語フレーズ", "英語で理解する", "実践的な例文"][index-1]
    dtext(d, (132, 612), small_label, 26, True, fg)
    d.line((132, 668, 890, 668), fill=fg, width=2)
    # Primary block (Japanese phrase / English explanation), then secondary block.
    size_p, lines_p = fit_block(d, primary, 746, 300, 84, 30)
    y = 700
    for line in lines_p:
        dtext(d, (132, y), line, size_p, True, fg)
        y += size_p + 18
    size_s, lines_s = fit_block(d, secondary, 746, 130, 44, 24, bold=False)
    y = 1030
    for line in lines_s:
        dtext(d, (132, y), line, size_s, False, fg)
        y += size_s + 14
    # Deliberate supporting visual, with a different learning cue per scene.
    # Bottom block sits above y=1600 to stay clear of IG's caption/action overlay.
    d.rounded_rectangle((88, 1230, 944, 1408), radius=32, fill="#ffffff")
    d.ellipse((116, 1268, 222, 1374), fill=mint if index != 2 else coral)
    if index == 1:
        # Speech waveform.
        for n, h in enumerate([16, 35, 58, 78, 44, 26]):
            x = 137 + n*12
            d.rounded_rectangle((x, 1321-h/2, x+6, 1321+h/2), radius=3, fill=ink)
        heading, detail = "声に出して読もう", "聞いて、一緒に繰り返して。"
    elif index == 2:
        d.line((144, 1320, 163, 1340, 197, 1300), fill=ink, width=8)
        heading, detail = "文は一つずつ", "シンプルなことが一番覚えやすい。"
    else:
        d.rounded_rectangle((141, 1295, 197, 1338), radius=10, outline=ink, width=4)
        d.polygon([(151, 1336), (151, 1351), (171, 1336)], fill=ink)
        heading, detail = "今度はあなたの番", "自分で文を作ってみよう。"
    dtext(d, (252, 1272), heading, 34, True, ink)
    dtext(d, (252, 1330), detail, 27, False, "#5d706a")
    for j, line in enumerate(wrap(d, title, 28, False, 800)[:2]):
        dtext(d, (88, 1445+j*36), line, 28, False, "#5d706a")
    # Three-part navigation gives the lesson a clear visual rhythm.
    for j, stage in enumerate(["読む", "理解する", "練習する"]):
        x = 88+j*290
        d.rounded_rectangle((x, 1545, x+270, 1553), radius=4, fill=coral if j+1 == index else "#ddd6cb")
        dtext(d, (x, 1573), stage, 24, True, ink if j+1 == index else "#86928b")
    im.save(dest)


def fetch_narration(url, dest):
    """Download a Qwen TTS voiceover. Fail-closed: the file must contain
    a real audio stream, otherwise the render aborts loudly."""
    if not isinstance(url, str) or not url.startswith("http"):
        raise ValueError("narration_audio URL must be an http(s) URL")
    run(["curl", "-sS", "--max-time", "120", "-o", str(dest), url])
    info = probe(dest)
    if not any(s.get("codec_type") == "audio" for s in info.get("streams", [])):
        raise ValueError("Downloaded narration has no audio stream: " + url[:80])


def probe(path):
    return json.loads(run(["ffprobe", "-v", "error", "-show_streams", "-show_format", "-of", "json", str(path)]))


def render(lesson, request_id, base_url, public, test_audio=False):
    validate(lesson, request_id)
    if not base_url.startswith("https://"):
        raise ValueError("base_url must start with https://")
    out = public / "reels" / request_id
    if out.exists():
        raise ValueError("request_id already exists; use a fresh unique ID")
    out.mkdir(parents=True)
    # (card label, primary text, secondary text, narration slot)
    sections = [
        ("日本語フレーズ", lesson["phrase"],
         f"{lesson['phrase_romaji']} — {lesson['meaning_en']}", "say_it"),
        ("英語で理解する", lesson["usage_en"], lesson["phrase"], "get_it"),
        ("実践的な例文", lesson["example"], lesson["example_en"], "use_it"),
    ]
    narration_urls = lesson.get("narration_audio") or {}
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        segments = []
        for index, (label, primary, secondary, slot) in enumerate(sections, 1):
            png, audio, video = [tmp / f"{index}.{ext}" for ext in ("png", "mp3", "mp4")]
            card(label, primary, secondary, lesson["title"], index, png)
            if test_audio:
                run(["ffmpeg", "-y", "-f", "lavfi", "-i", "sine=frequency=440:duration=2", str(audio)])
            else:
                url = narration_urls.get(slot)
                if not url:
                    raise ValueError(f"Lesson is missing narration_audio.{slot}; Qwen TTS voiceover required")
                fetch_narration(url, audio)
            duration = float(probe(audio)["format"]["duration"]) + 0.5
            run(["ffmpeg", "-y", "-loop", "1", "-framerate", "30", "-i", str(png), "-i", str(audio),
                "-map", "0:v:0", "-map", "1:a:0", "-vf",
                f"zoompan=z='min(1.025,1+on*0.00006)':x='iw/2-iw/zoom/2':y='ih/2-ih/zoom/2':d=1:s=1080x1920:fps=30,fade=t=out:st={duration-0.18}:d=0.18,format=yuv420p", "-af", "apad",
                "-t", str(duration), "-c:v", "libx264", "-preset", "fast", "-crf", "23",
                "-maxrate", "5M", "-bufsize", "10M", "-c:a", "aac", "-b:a", "128k", "-ar", "48000", "-ac", "2", "-movflags", "+faststart", str(video)])
            segments.append(video)
        listing = tmp / "concat.txt"
        listing.write_text("".join(f"file '{p.as_posix()}'\n" for p in segments))
        target = out / "reel.mp4"
        run(["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", str(listing), "-c", "copy", "-movflags", "+faststart", str(target)])
    cover = out / "cover.jpg"
    run(["ffmpeg", "-y", "-ss", "1.0", "-i", str(target), "-frames:v", "1", "-q:v", "3", str(cover)])
    data = probe(target)
    vs = next(s for s in data["streams"] if s["codec_type"] == "video")
    aud = next(s for s in data["streams"] if s["codec_type"] == "audio")
    if (vs["width"], vs["height"], vs["codec_name"], aud["codec_name"]) != (1080, 1920, "h264", "aac"):
        raise ValueError("Output media validation failed")
    if target.stat().st_size > 90 * 1024 * 1024:
        raise ValueError("Video exceeds renderer's 90 MiB limit")
    duration = float(data["format"]["duration"])
    if duration > 120:
        raise ValueError("Lesson exceeds renderer's 120 second limit")
    manifest = {"request_id": request_id, "status": "ready", "video_url": f"{base_url.rstrip('/')}/reels/{request_id}/reel.mp4",
        "cover_url": f"{base_url.rstrip('/')}/reels/{request_id}/cover.jpg",
        "design_version": 2, "title": lesson["title"], "duration_seconds": round(duration, 2), "width": 1080, "height": 1920,
        "created_at": datetime.now(timezone.utc).isoformat(), "test_audio": test_audio}
    requests = public / "requests"
    requests.mkdir(exist_ok=True)
    (requests / f"{request_id}.json").write_text(json.dumps(manifest, indent=2))
    (public / "latest.json").write_text(json.dumps(manifest, indent=2))
    (public / ".nojekyll").touch()
    (public / "index.html").write_text("<!doctype html><title>Japanese English Reel Renderer</title><p>Japanese English reel renderer is running.</p>")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--lesson", type=Path)
    parser.add_argument("--request-id", default=os.environ.get("REQUEST_ID"))
    parser.add_argument("--base-url", default=os.environ.get("BASE_URL"))
    parser.add_argument("--public", type=Path, default=Path("public"))
    parser.add_argument("--test-audio", action="store_true", help="Offline verification only; generates tones, not narration")
    args = parser.parse_args()
    lesson = json.loads(args.lesson.read_text() if args.lesson else os.environ["LESSON_JSON"])
    render(lesson, args.request_id, args.base_url, args.public, args.test_audio)
